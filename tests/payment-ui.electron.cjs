const {app,BrowserWindow}=require('electron')
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict')
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'clinic-payment-ui-'))
app.setPath('userData',path.join(directory,'user-data'))
async function run() {
  await require('esbuild').build({entryPoints:[path.join(__dirname,'payment-ui-entry.tsx')],outfile:path.join(directory,'ui.js'),bundle:true,format:'iife',platform:'browser',jsx:'automatic',plugins:[{name:'test-currency',setup(build){
    build.onResolve({filter:/^@\/contexts\/CurrencyContext$/},()=>({path:'currency',namespace:'test'}))
    build.onLoad({filter:/.*/,namespace:'test'},()=>({contents:'export const useCurrency=()=>({formatAmount:n=>n.toFixed(2)+" $"})',loader:'js'}))
  }}]})
  fs.writeFileSync(path.join(directory,'index.html'),'<html lang="ar" dir="rtl"><body><div id="root"></div><script src="ui.js"></script></body></html>')
  const win=new BrowserWindow({show:false,width:1000,height:800,webPreferences:{contextIsolation:true,nodeIntegration:false}})
  await win.loadFile(path.join(directory,'index.html'))
  const js=code=>win.webContents.executeJavaScript(code,true)
  const until=condition=>js(`new Promise((resolve,reject)=>{let tries=0;const poll=()=>{if(${condition})resolve(true);else if(++tries>100)reject(new Error('UI timeout'));else setTimeout(poll,20)};poll()})`)
  const button=label=>`[...document.querySelectorAll('button')].find(b=>b.textContent==='${label}')`
  const click=label=>js(`${button(label)}.click()`)
  await until(`${button('دفع كامل المبلغ فوراً')}`)
  await click('دفع كامل المبلغ فوراً')
  await until(`document.querySelector('[role=alertdialog]')`)
  assert.ok(await js(`document.body.textContent.includes('50.00 $')`))
  await click('إلغاء')
  await until(`!document.querySelector('[role=alertdialog]')`)
  assert.equal(await js('window.harness.calls'),0)
  console.log('PASS: cancellation creates no receipt')
  await js("window.harness.mode='fail'")
  await click('دفع كامل المبلغ فوراً');await until(`${button('تأكيد الدفع الكامل')}`)
  await click('تأكيد الدفع الكامل');await until(`document.querySelector('[role=alert]')`)
  assert.equal(await js('window.harness.calls'),1)
  assert.ok(await js("document.body.textContent.includes('فشل تجريبي')"))
  assert.ok(await js("!!document.querySelector('[role=alertdialog]')"))
  console.log('PASS: failure keeps confirmation and shows error')
  await js("window.harness.mode='pending';const s=document.querySelector('select');s.value='bank_transfer';s.dispatchEvent(new Event('change',{bubbles:true}))")
  await js(`${button('تأكيد الدفع الكامل')}.click();${button('تأكيد الدفع الكامل')}.click()`)
  await until('window.harness.calls===2')
  assert.equal(await js('window.harness.calls'),2)
  assert.equal(await js('window.harness.method'),'bank_transfer')
  assert.equal(await js(`${button('تأكيد الدفع الكامل')}.disabled`),true)
  await js('window.harness.resolve()');await until(`!document.querySelector('[role=alertdialog]')`)
  console.log('PASS: double click submits once, chosen method is retained, success closes confirmation')
  assert.ok(await js('window.harness.keyFor({amount:50})===window.harness.keyFor({amount:50})'))
  assert.ok(await js('const previous=window.harness.keyFor({amount:50});window.harness.keyFor.reset();previous!==window.harness.keyFor({amount:50})'))
  console.log('PASS: retries retain their request key; a new successful operation can use a fresh key')
  for(const amount of ['0','-1','NaN','Infinity','1.001']) {
    await js(`window.harness.render(${amount})`)
    await until(`${button('دفع كامل المبلغ فوراً')}.disabled`)
  }
  console.log('PASS: invalid and zero costs disable immediate payment')
  win.close()
  app.exit(0)
}
app.whenReady().then(run).catch(error=>{console.error(error);app.exit(1)})
