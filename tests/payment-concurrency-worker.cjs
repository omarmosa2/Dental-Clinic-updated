const {parentPort,workerData}=require('node:worker_threads')
const Database=require('better-sqlite3')
const {DatabaseService}=require('../src/services/databaseService.js')
const service=Object.create(DatabaseService.prototype)
service.db=new Database(workerData.file)
service.db.pragma('busy_timeout = 5000')
const barrier=new Int32Array(workerData.barrier)
parentPort.postMessage({ready:true})
Atomics.wait(barrier,0,0)
service.createPayment({patient_id:'p',tooth_treatment_id:'t',amount:30,payment_method:'cash',payment_date:'2026-11-18',status:'completed',request_id:workerData.requestId})
  .then(result=>parentPort.postMessage({ok:true,id:result.id}))
  .catch(error=>parentPort.postMessage({ok:false,error:error.message}))
  .finally(()=>service.db.close())
